using System;
using System.Collections.Generic;
using System.Linq;

namespace Manufacture.Models.Domain
{
    public enum RouteSheetStatus
    {
        Ordered = 0,
        LoadedOnRoute = 1,
        Reconciled = 2,
        Closed = 3
    }

    /// <summary>
    /// Line item tracking route inventory flow for a single SKU.
    /// Active route inventory = yesterday's unsold closing stock + today's newly loaded stock.
    /// </summary>
    public class RouteSKUItem
    {
        public int ProductId { get; set; }
        public string ProductCode { get; set; } = string.Empty;
        public string ProductName { get; set; } = string.Empty;
        public ProductType Category { get; set; } = ProductType.Bread;
        public decimal UnitSellingPrice { get; set; }

        /// <summary>Initial request placed by the sales rep.</summary>
        public int RepOrderRequestedQty { get; set; }

        /// <summary>Unsold closing stock retained in vehicle from previous route.</summary>
        public int YesterdayClosingStock { get; set; }

        /// <summary>Physical quantity verified and signed off by dispatch staff.</summary>
        public int TodayNewlyLoadedQty { get; set; }

        /// <summary>Active inventory available to sell on the route today.</summary>
        public int TotalActiveInventory => YesterdayClosingStock + TodayNewlyLoadedQty;

        /// <summary>Actual verified units sold to route customers/supermarkets.</summary>
        public int QtySold { get; set; }

        /// <summary>Unsold closing stock returning in vehicle to be carried over.</summary>
        public int QtyReturned { get; set; }

        /// <summary>Spoiled, squashed or damaged goods written off with credit.</summary>
        public int QtyDamaged { get; set; }

        /// <summary>Total expected monetary value generated by this SKU.</summary>
        public decimal ExpectedItemRevenue => QtySold * UnitSellingPrice;

        /// <summary>Validates that sold + returned + damaged equals active inventory.</summary>
        public bool IsCountBalanced => (QtySold + QtyReturned + QtyDamaged) == TotalActiveInventory;
    }

    /// <summary>
    /// Daily route ledger and financial reconciliation sheet for a field sales representative.
    /// Reconciles loaded stock, sales, returns, and aggregated lump-sum collections.
    /// </summary>
    public class DailyRepRouteSheet
    {
        public int Id { get; set; }
        public string RouteSheetRef { get; set; } = string.Empty; // e.g. "RTE-20261014-001"
        public DateTime Date { get; set; } = DateTime.UtcNow.Date;
        public int RepId { get; set; }
        public string RepName { get; set; } = string.Empty;
        public string RepCode { get; set; } = string.Empty; // e.g. "REP-001"
        public string RouteName { get; set; } = string.Empty;
        public string VehicleRegNumber { get; set; } = string.Empty;
        public string PosTerminalCode { get; set; } = string.Empty;

        public List<RouteSKUItem> Items { get; set; } = new();

        // Financial Ledger
        public decimal PreviousAccountBalance { get; set; }

        // Lump-sum payments collected on route (NO SKU breakdown)
        public decimal CashCollected { get; set; }
        public decimal BankTransferCollected { get; set; }
        public decimal PosTerminalCollected { get; set; }

        public decimal TotalExpectedSalesRevenue => Items.Sum(i => i.ExpectedItemRevenue);
        public decimal TotalPaymentsCollectedToday => CashCollected + BankTransferCollected + PosTerminalCollected;

        /// <summary>
        /// Net updated running balance owed by the rep account:
        /// Previous Balance + Expected Sales - Total Payments.
        /// </summary>
        public decimal NewOutstandingAccountBalance =>
            PreviousAccountBalance + TotalExpectedSalesRevenue - TotalPaymentsCollectedToday;

        public RouteSheetStatus Status { get; set; } = RouteSheetStatus.Ordered;

        public string? SignedOffByDispatcher { get; set; }
        public DateTime? SignedOffAt { get; set; }

        public string? ReconciledBy { get; set; }
        public DateTime? ReconciledAt { get; set; }

        public string Notes { get; set; } = string.Empty;
    }

    /// <summary>
    /// Supermarket and institutional account with agreed custom pricing and credit management.
    /// </summary>
    public class SupermarketAccount
    {
        public int Id { get; set; }
        public int CustomerId { get; set; }
        public string AccountName { get; set; } = string.Empty;
        public string ContactPerson { get; set; } = string.Empty;
        public string PhoneNumber { get; set; } = string.Empty;
        public string Address { get; set; } = string.Empty;
        public int AssignedRepId { get; set; }
        public string AssignedRepName { get; set; } = string.Empty;
        public decimal CurrentOutstandingCredit { get; set; }
        public decimal CreditLimit { get; set; } = 250000m;
        public string PaymentTerms { get; set; } = "Net 15 Days";
        public bool IsActive { get; set; } = true;

        /// <summary>
        /// Map of RecipeId/ProductId -> Custom Agreed Selling Price.
        /// Overrides master recipe price when billing this specific account.
        /// </summary>
        public Dictionary<int, decimal> CustomAgreedPrices { get; set; } = new();
    }
}
