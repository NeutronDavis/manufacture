using System.ComponentModel.DataAnnotations;
using Manufacture.Models.Domain;

namespace Manufacture.Models.DTOs
{
    public class SupplierDto
    {
        public int Id { get; set; }
        [Required]
        public string Name { get; set; } = string.Empty;
        [Required]
        public string ContactPerson { get; set; } = string.Empty;
        [Required, Phone]
        public string PhoneNumber { get; set; } = string.Empty;
        [EmailAddress]
        public string Email { get; set; } = string.Empty;
        [Required]
        public string SupplyCategory { get; set; } = "Flour & Grains";
        public string Address { get; set; } = string.Empty;
        public bool IsActive { get; set; } = true;
    }

    public class InventoryItemDto
    {
        public int Id { get; set; }

        // Generated by InventoryService when a new stock item is saved.
        public string ItemCode { get; set; } = string.Empty;

        [Required]
        public string Name { get; set; } = string.Empty;

        [Required]
        public string Category { get; set; } = "Raw Materials";

        [Required]
        public string Unit { get; set; } = "Bags (50kg)";

        [Range(0, 1000000)]
        public decimal QuantityInStock { get; set; }

        [Range(0, 1000000)]
        public decimal ReorderThreshold { get; set; }

        [Range(0, 10000000)]
        public decimal UnitCostPrice { get; set; }

        public int? PreferredSupplierId { get; set; }

        public string? PreferredSupplierName { get; set; }

        public DateTime LastRestockedDate { get; set; } = DateTime.UtcNow;

        public bool IsActive { get; set; } = true;

        public bool IsLowStock => QuantityInStock <= ReorderThreshold;
    }

    public class InventoryRecipeUsageDto
    {
        public int Id { get; set; }
        public string Name { get; set; } = string.Empty;
        public string Code { get; set; } = string.Empty;
        public decimal ExpectedYield { get; set; }
        public string OutputUnit { get; set; } = string.Empty;
    }

    public class StockMovementDto
    {
        public int Id { get; set; }
        public int InventoryItemId { get; set; }
        public string ItemCode { get; set; } = string.Empty;
        public string ItemName { get; set; } = string.Empty;
        public string Unit { get; set; } = string.Empty;
        public string MovementType { get; set; } = string.Empty;
        public decimal Quantity { get; set; }
        public decimal BalanceAfter { get; set; }
        public int? StoreRequestId { get; set; }
        public string? ReferenceNumber { get; set; }
        public string? Notes { get; set; }
        public string PerformedBy { get; set; } = string.Empty;
        public DateTime CreatedAt { get; set; }
    }

    public class StoreRequestItemDto
    {
        public int Id { get; set; }
        public int StoreRequestId { get; set; }
        public int InventoryItemId { get; set; }
        public string ItemName { get; set; } = string.Empty;
        public string Unit { get; set; } = string.Empty;

        [Range(0, 1000000)]
        public decimal RequestedQuantity { get; set; }

        public decimal IssuedQuantity { get; set; }
    }

    public class StoreRequestDto
    {
        public int Id { get; set; }
        public string RequestNumber { get; set; } = string.Empty;

        [Required]
        public string RequestedBy { get; set; } = string.Empty;

        public string Department { get; set; } = "Bakery Floor";

        [Required]
        public string Purpose { get; set; } = string.Empty;

        public List<StoreRequestItemDto> Items { get; set; } = new();

        public StoreRequestStatus Status { get; set; } = StoreRequestStatus.Pending;

        public DateTime RequestedAt { get; set; } = DateTime.UtcNow;

        public string? ApprovedBy { get; set; }

        public DateTime? ApprovedAt { get; set; }

        public string? RejectionReason { get; set; }
    }
}
